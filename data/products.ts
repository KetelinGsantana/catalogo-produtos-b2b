// EANs use the GS1 prefix 200 (reserved for internal use), which is not assigned to any company.

export type ProductStatus = "AVAILABLE" | "OUT OF STOCK"

export interface Product {
  name: string
  category: string
  /** Net weight of the package */
  size: string
  /** Wholesale price per unit, in USD */
  wholesalePrice: number
  /** Price before a discount, shown struck through */
  originalWholesalePrice?: number
  /** Suggested retail price per unit, in USD */
  retailPrice: number
  /** Retail price divided by wholesale price */
  markup: number
  /** Expiration date of the current batch (YYYY-MM-DD) */
  expirationDate: string
  /** Months left until the batch expires */
  monthsToExpiry: number
  /** Barcode (EAN-13) */
  ean: string
  /** Mercosur tax classification code */
  ncm: string
  status: ProductStatus
  image?: string
  /** Highlight label, e.g. "SALE" or "NEW" */
  tag?: string
}

